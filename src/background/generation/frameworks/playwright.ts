import type { GeneratedFile, GeneratedTestCase, ProjectMeta, TestFrameworkAdapter } from '@shared/types';
import { getResourcePath } from './pathing';

const headerValueExpr = (value: string): string =>
  value === 'Bearer {{API_TOKEN}}'
    ? "(process.env.API_TOKEN ? `Bearer ${process.env.API_TOKEN}` : 'Bearer replace-me')"
    : value === '{{API_KEY}}'
      ? "(process.env.API_KEY || 'replace-me')"
      : value === '{{CSRF_TOKEN}}'
        ? "(process.env.CSRF_TOKEN || 'replace-me')"
        : JSON.stringify(value);

const toHeadersObject = (headers: Record<string, string>): string => {
  const entries = Object.entries(headers);
  if (!entries.length) {
    return '{}';
  }
  return `{
      ${entries.map(([key, value]) => `${JSON.stringify(key)}: ${headerValueExpr(value)}`).join(',\n      ')}
    }`;
};

const PLAYWRIGHT_METHODS: Record<string, string> = {
  get: 'get',
  post: 'post',
  put: 'put',
  patch: 'patch',
  delete: 'delete',
  head: 'head'
};

export class PlaywrightFrameworkAdapter implements TestFrameworkAdapter {
  readonly framework = 'playwright' as const;

  render(tests: GeneratedTestCase[], projectMeta: ProjectMeta): GeneratedFile[] {
    const grouped = new Map<string, GeneratedTestCase[]>();
    const groupToPath = new Map<string, string>();

    for (const test of tests) {
      const pathMeta = getResourcePath(test.request.path);
      const key = `${pathMeta.resource}_${test.request.method.toLowerCase()}_${pathMeta.leaf}`;
      if (!grouped.has(key)) {
        grouped.set(key, []);
        groupToPath.set(key, `tests/${pathMeta.resource}/${test.request.method.toLowerCase()}-${pathMeta.leaf}.spec.ts`);
      }
      grouped.get(key)?.push(test);
    }

    return [...grouped.entries()].map(([groupKey, cases]) => {
      const blocks = cases
        .map((testCase) => {
          const method = testCase.request.method.toLowerCase();
          const requestMethod = PLAYWRIGHT_METHODS[method] ?? 'fetch';
          const headers = toHeadersObject(testCase.request.headers ?? {});
          const hasHeaders = Object.keys(testCase.request.headers ?? {}).length > 0;
          const hasQuery = Object.keys(testCase.request.query ?? {}).length > 0;
          const hasBody = testCase.request.body !== undefined && testCase.request.body !== null;

          const optionLines: string[] = [];
          if (hasHeaders) {
            optionLines.push(`    headers: ${headers}`);
          }
          if (hasQuery) {
            optionLines.push(`    params: ${JSON.stringify(testCase.request.query, null, 2).replace(/\n/g, '\n    ')}`);
          }
          if (hasBody) {
            optionLines.push(`    data: ${JSON.stringify(testCase.request.body, null, 2).replace(/\n/g, '\n    ')}`);
          }
          const optionsArg = optionLines.length ? `, {\n${optionLines.join(',\n')}\n  }` : '';

          const containsAsserts = (testCase.expected.contains ?? [])
            .map((value) => `  expect(text).toContain(${JSON.stringify(value)});`)
            .join('\n');
          const ctAssert = testCase.expected.contentType
            ? `  expect(response.headers()['content-type'] || '').toContain(${JSON.stringify(testCase.expected.contentType)});`
            : '';
          const headerAsserts = Object.entries(testCase.expected.responseHeaders ?? {})
            .map(([k, v]) => `  expect(response.headers()[${JSON.stringify(k.toLowerCase())}]).toBe(${JSON.stringify(v)});`)
            .join('\n');

          return `test(${JSON.stringify(testCase.title)}, async ({ request }) => {
  // ${testCase.category} — trust: ${testCase.trustLabel ?? 'heuristic'} (${testCase.trustScore ?? 0})
  const response = await request.${requestMethod}(\`${'${BASE_URL}'}${testCase.request.path}\`${optionsArg});
  expect(response.status()).toBe(${testCase.expected.status});
  const text = await response.text();
${ctAssert}
${headerAsserts}
${containsAsserts}
});`;
        })
        .join('\n\n');

      return {
        path: groupToPath.get(groupKey) ?? `tests/${groupKey}.spec.ts`,
        content: `/**
 * Generated by APItiser for ${projectMeta.repo.owner}/${projectMeta.repo.repo}
 * Set API_BASE_URL before running.
 * Replace placeholder auth values like Bearer {{API_TOKEN}} with real environment-backed credentials.
 */
import { test, expect } from '@playwright/test';

const BASE_URL = process.env.API_BASE_URL || 'http://localhost:3000';

test.describe(${JSON.stringify(groupKey)}, () => {
${blocks}
});
`
      };
    });
  }

  renderReadme(projectMeta: ProjectMeta): GeneratedFile {
    const validationLine = projectMeta.validationSummary
      ? `Validation: ${projectMeta.validationSummary.passed}/${projectMeta.validationSummary.attempted} passed`
      : 'Validation: not run';
    const readinessNotes = projectMeta.readinessNotes?.length
      ? `\n## Readiness Notes\n\n${projectMeta.readinessNotes.map((note) => `- ${note}`).join('\n')}\n`
      : '';
    return {
      path: 'README.md',
      content: `# APItiser Generated Playwright API Tests

Generated at: ${projectMeta.generatedAt}
Repository: ${projectMeta.repo.owner}/${projectMeta.repo.repo}
Endpoints: ${projectMeta.endpointCount}
Readiness: ${projectMeta.readiness ?? 'review_required'}
${validationLine}

## Run

\`\`\`bash
npm install
export API_TOKEN=replace-me
API_BASE_URL=http://localhost:3000 npx playwright test
\`\`\`
${readinessNotes}`
    };
  }

  renderSupportFiles(_projectMeta?: ProjectMeta): GeneratedFile[] {
    return [
      {
        path: 'playwright.config.ts',
        content: `import { defineConfig } from '@playwright/test';\n\nexport default defineConfig({\n  testDir: './tests',\n  timeout: 30000\n});\n`
      },
      {
        path: 'package.json',
        content: `${JSON.stringify({
          name: 'apitiser-generated-tests',
          private: true,
          scripts: { test: 'playwright test' },
          devDependencies: { '@playwright/test': '^1.48.0' }
        }, null, 2)}\n`
      }
    ];
  }
}
